//! События ввода от ОС в собственных типах (типы `winit` наружу не выходят).

/// Событие ввода. Координаты — в физических пикселях окна, (0, 0) — левый верхний угол.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum InputEvent {
    Key {
        key: Key,
        pressed: bool,
    },
    MouseButton {
        button: MouseButton,
        pressed: bool,
    },
    CursorMoved {
        x: f32,
        y: f32,
    },
    /// Колесо мыши: строки, положительное — от себя.
    MouseWheel {
        lines: f32,
    },
    /// Прокрутка двумя пальцами по тачпаду: пиксели по осям.
    TrackpadScroll {
        x: f32,
        y: f32,
    },
    /// Щипок на тачпаде (macOS): изменение масштаба, положительное — «раздвинуть пальцы».
    TrackpadPinch {
        delta: f32,
    },
    Touch {
        id: u64,
        phase: TouchPhase,
        x: f32,
        y: f32,
    },
    /// Введённый символ (с учётом раскладки и Shift) — для текстовых полей.
    Char(char),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MouseButton {
    Left,
    Right,
    Middle,
    Other(u16),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum TouchPhase {
    Started,
    Moved,
    Ended,
    Cancelled,
}

