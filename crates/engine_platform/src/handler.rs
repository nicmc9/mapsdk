use crate::{Instant, PlatformWindow, WindowSize};

/// Что платформа сообщает верхнему слою (ядру движка).
///
/// Платформа не знает о движке: она вызывает методы этого трейта, а ядро их реализует.
/// Так зависимость остаётся направленной вниз (ядро → платформа).
// [Rust] `'static` — тип не содержит ссылок на временные данные. Обработчик живёт
// внутри цикла событий до конца программы, поэтому короткоживущие ссылки в нём запрещены.
pub trait PlatformHandler: 'static {
    /// Окно создано или приложение вернулось из фона. С этого момента можно создавать
    /// GPU-surface. На Android и iOS вызывается после каждого возврата из фона.
    fn resumed(&mut self, window: &PlatformWindow);

    /// Приложение ушло в фон. На Android native-окно уничтожается сразу после
    /// возврата из этого метода: всё, что рисует в окно, должно быть остановлено здесь.
    fn suspended(&mut self);

    /// Изменился физический размер окна или плотность пикселей.
    fn resized(&mut self, size: WindowSize, scale_factor: f64);

    /// Очередь событий ОС пуста — время выполнить кадр. Возвращает, когда вызвать снова.
    fn update(&mut self) -> NextUpdate;

    /// Пользователь закрывает окно. `true` — разрешить выход.
    fn close_requested(&mut self) -> bool {
        true
    }

    /// Цикл событий завершается. Последний шанс корректно остановить потоки.
    fn exiting(&mut self);
}

/// Когда платформе снова вызвать [`PlatformHandler::update`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NextUpdate {
    /// Сразу, без ожидания.
    Immediately,
    /// В указанный момент или раньше, если придёт событие ОС.
    At(Instant),
    /// Только после следующего события ОС.
    WaitForEvents,
    /// Завершить приложение.
    Exit,
}
